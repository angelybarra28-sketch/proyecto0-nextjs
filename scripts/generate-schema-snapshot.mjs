import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'supabase', 'migrations');
const outFile = join(root, 'supabase', 'schema.sql');

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

if (files.length === 0) {
  throw new Error(`No SQL migrations found in ${migrationsDir}`);
}

const SEPARATOR = '============================================';
const parts = [
  '-- supabase/schema.sql',
  '-- AUTO-GENERATED snapshot. Do NOT edit this file manually.',
  `-- Regenerate with: npm run schema:generate (scripts/generate-schema-snapshot.mjs).`,
  `--`,
  `-- Built from ${files.length} versioned migrations (supabase/migrations/), in apply order.`,
  `-- Applying this file to a fresh Supabase project reproduces the exact state of all`,
  `-- migrations (equivalent to: supabase db reset).`,
  `--`,
  `-- If a DB object exists only in the running database (created by hand, never added`,
  `-- as a migration), it must be incorporated as a NEW versioned migration, not`,
  `-- backported into this snapshot, to avoid recreating a dual-source-of-truth`,
  `-- situation. The high-availability trigger was resolved that way in`,
  `-- 202608060001_handle_new_auth_user.sql.`,
  `--`,
  `-- Previous hand-maintained snapshot kept at: supabase/schema.sql.backup-fase1.`,
  '',
];

for (const f of files) {
  const raw = readFileSync(join(migrationsDir, f), 'utf8')
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n');
  parts.push(
    `-- ${SEPARATOR}`,
    `-- Migration: ${f}`,
    `-- ${SEPARATOR}`,
    raw.trimEnd(),
    '',
  );
}

const out = parts.join('\n').trimEnd() + '\n';
writeFileSync(outFile, out, 'utf8');

const bytes = statSync(outFile).size;
const lines = out.split('\n').length;
console.log(`Regenerated ${outFile}`);
console.log(`  migrations: ${files.length}`);
console.log(`  lines:      ${lines}`);
console.log(`  bytes:      ${bytes}`);
